import { test, expect } from '@playwright/test';
import { seed, open, stored, TODAY } from './helpers';

test('Kraftvorlage erstellen, bearbeiten, starten und unabhängig abschließen', async ({ page }) => {
  await seed(page); await open(page, '/?go=strength');
  await page.locator('[data-act="strength-new"]').click();
  await page.fill('#strength-name', 'Ganzkörper');
  await page.fill('#strength-0-name', 'Kniebeuge');
  await page.fill('#strength-0-sets', '3');
  await page.fill('#strength-0-reps', '8–10');
  await page.fill('#strength-0-kg', '0');
  await page.fill('#strength-0-restSec', '90');
  await page.locator('[data-act="strength-row-add"]').click();
  await page.fill('#strength-1-name', 'Rudern');
  await page.fill('#strength-1-sets', '3');
  await page.fill('#strength-1-reps', '10');
  await page.locator('[data-act="strength-move"][data-i="1"][data-dir="-1"]').click();
  await page.locator('[data-act="strength-save"]').click();
  let state = await stored(page);
  const id = Object.keys(state.strengthTemplates)[0];
  expect(state.strengthTemplates[id].exercises.map((e: any) => e.name)).toEqual(['Rudern', 'Kniebeuge']);
  await page.reload();
  await expect(page.locator('[data-strength-template]')).toContainText('Ganzkörper');
  await page.locator('[data-act="strength-edit"]').click();
  await page.fill('#strength-name', 'Ganzkörper A');
  await page.locator('[data-act="strength-save"]').click();
  await page.locator('[data-act="strength-copy"]').click();
  await page.locator('[data-act="strength-save"]').click();
  await expect(page.locator('[data-strength-template]')).toHaveCount(2);
  const copy = page.locator('[data-strength-template]').filter({ has: page.locator('h2', { hasText: '(Kopie)' }) });
  await copy.locator('[data-act="strength-delete"]').click();
  await copy.locator('[data-act="strength-delete"]').click();
  await expect(page.locator('[data-strength-template]')).toHaveCount(1);
  await page.locator('[data-act="strength-start"]').click();
  await page.fill('#strength-date', TODAY);
  await page.locator('[data-act="strength-start-confirm"]').click();
  await expect(page.locator('#sheetPanel')).toContainText('Entwurf');
  state = await stored(page);
  const workoutId = state.customWorkouts[TODAY].find((x: any) => x.strengthTemplateId === id).id;
  expect(state.customWorkouts[TODAY].find((x: any) => x.id === workoutId).completed).toBe(false);
  await page.locator('[data-ch="fd-ex"][data-i="0"][data-f="kg"]').fill('25');
  await page.locator('[data-ch="fd-ex"][data-i="0"][data-f="kg"]').blur();
  await page.locator('[data-act="custom-complete"]').click();
  await expect.poll(async () => (await stored(page)).customWorkouts[TODAY].find((x: any) => x.id === workoutId).completed).toBe(true);
  state = await stored(page);
  expect(state.strengthTemplates[id].exercises[0].kg).toBeNull();
  expect(state.customWorkouts[TODAY].find((x: any) => x.id === workoutId).metrics.exercises[0].kg).toBe(25);
  await page.reload();
  expect((await stored(page)).customWorkouts[TODAY].find((x: any) => x.id === workoutId).completed).toBe(true);
});

test('Vorlage validieren und in geplanter Krafteinheit übernehmen und speichern', async ({ page }) => {
  await seed(page, { extra: d => { d.strengthTemplates = { t1: { id: 't1', name: 'Oberkörper', updatedAt: 1, exercises: [{ name: 'Bankdrücken', sets: 3, reps: '8', kg: 40, restSec: 120 }] } }; } });
  await open(page, '/?go=strength');
  await page.locator('[data-act="strength-new"]').click();
  await page.locator('[data-act="strength-save"]').click();
  await expect(page.locator('#sheet')).toBeVisible();
  expect(Object.keys((await stored(page)).strengthTemplates)).toHaveLength(1);
  await page.getByRole('dialog').getByRole('button', { name: 'Schließen', exact: true }).click();
  await page.locator('.tab[data-tab="plan"]').click();
  const target = await page.evaluate(() => { const p = JSON.parse(localStorage.getItem('ec_plan')!); for (let i = 0; i < p.weeks.length; i++) { const s = p.weeks[i].days.flatMap((d: any) => d.sessions).find((s: any) => s.sport === 'strength'); if (s) return { week: i, sid: s.id }; } throw new Error('Keine geplante Krafteinheit'); });
  await page.locator(`[data-act="plan-week"][data-i="${target.week}"]`).click();
  await page.locator(`[data-act="sess-open"][data-sid="${target.sid}"]`).first().click();
  await page.selectOption('[data-template-select]', 't1');
  await page.locator('[data-act="fd-template-apply"]').click();
  await expect(page.locator('[data-ch="fd-ex"][data-f="name"]').first()).toHaveValue('Bankdrücken');
  await page.locator('[data-act="fd-template-save"]').click();
  await page.fill('#strength-name', 'Aus meinem Plan');
  await page.locator('[data-act="strength-save"]').click();
  expect(Object.values((await stored(page)).strengthTemplates).some((x: any) => x.name === 'Aus meinem Plan')).toBe(true);
});
